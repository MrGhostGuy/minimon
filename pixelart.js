// Draw a grid-based sprite onto a canvas context
function drawGrid(ctx,x,y,size,grid,palette){
  const rows=grid.length,cols=grid[0]?grid[0].length:0;
  if(!rows||!cols)return;
  const px=size/Math.max(rows,cols);
  for(let r=0;r<rows;r++){
    for(let c=0;c<cols;c++){
      const v=grid[r][c];
      if(v==='.'||v===0)continue;
      const col=palette[parseInt(v)];
      if(!col)continue;
      ctx.fillStyle=rgb(col);
      ctx.fillRect(Math.floor(x+c*px),Math.floor(y+r*px),Math.ceil(px),Math.ceil(px));
    }
  }
}

// Draw creature sprite with type-colored shading
function drawCreature(ctx,x,y,size,dex,isEnemy){
  const grid=CREATURE_SPRITES[dex];
  if(!grid)return;
  const c=CREATURES[dex];
  if(!c)return;
  const tc=TYPE_COLORS[c.types[0]]||[200,200,200];
  // Build palette: type color variants
  const palette=[
    [0,0,0],// 0=empty
    [Math.min(255,tc[0]+80),Math.min(255,tc[1]+80),Math.min(255,tc[2]+80)],// 1=highlight
    tc,// 2=mid
    [Math.max(0,tc[0]-60),Math.max(0,tc[1]-60),Math.max(0,tc[2]-60)]// 3=shadow
  ];
  drawGrid(ctx,x,y,size,grid,palette);
}

// Draw NPC sprite
function drawNPC(ctx,x,y,size,npcType){
  const grid=NPC_PATTERNS[npcType]||NPC_PATTERNS.talker;
  const pal=NPC_COLORS[npcType]||NPC_COLORS.talker;
  drawGrid(ctx,x,y,size,grid,pal);
}

// Draw player overworld sprite
function drawPlayer(ctx,x,y,size){
  drawGrid(ctx,x,y,size,PLAYER_SPRITE,PLAYER_PALETTE);
}
