def draw_creature_pixel_art(screen, x, y, size, dex_num, is_enemy=False, palette=None):
    sprite = CREATURE_SPRITES.get(dex_num)
    if sprite is None:
        sprite = CREATURE_SPRITES[85]

    type_key = CREATURE_PALETTES.get(dex_num, "Normal")
    if palette is None:
        pal = PALETTES.get(type_key, PALETTES["Normal"])
    else:
        pal = palette

    grid = [row[:] for row in sprite]
    if is_enemy:
        grid = [row[::-1] for row in grid]

    rows = len(grid)
    cols = len(grid[0]) if rows > 0 else 0
    if rows == 0 or cols == 0:
        return

    px_size = size / max(rows, cols)

    for r in range(rows):
        for c in range(cols):
            val = grid[r][c]
            if val == 0:
                continue
            color = pal[val]
            rx = int(x + c * px_size)
            ry = int(y + r * px_size)
            rw = int((c + 1) * px_size) - int(c * px_size)
            rh = int((r + 1) * px_size) - int(r * px_size)
            if rw < 1:
                rw = 1
            if rh < 1:
                rh = 1
            pygame.draw.rect(screen, color, (rx, ry, rw, rh))
